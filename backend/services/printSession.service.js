async markFilesUploaded(sessionId) {
  // First make sure at least one file exists
  const {
    count,
    error: countError,
  } = await supabaseAdmin
    .from("print_session_files")
    .select("id", {
      count: "exact",
      head: true,
    })
    .eq("session_id", sessionId);

  if (countError) {
    return {
      error: countError,
    };
  }

  if (!count || count < 1) {
    return {
      error: {
        message:
          "Cannot mark files uploaded without files",
      },
    };
  }

  // Move session forward
  return await supabaseAdmin
    .from("print_sessions")
    .update({
      status: "files_uploaded",
    })
    .eq("id", sessionId)
    .eq("status", "files_uploading")
    .select()
    .single();
}


