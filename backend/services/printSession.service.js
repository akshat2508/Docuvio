async startFileUpload(sessionToken) {
  // 1. Find session
  const {
    data: session,
    error: sessionError,
  } = await supabaseAdmin
    .from("print_sessions")
    .select("*")
    .eq("session_token", sessionToken)
    .single();

  if (sessionError || !session) {
    return {
      error: {
        message: "Print session not found",
      },
    };
  }

  // 2. Validate current state
  if (session.status !== "customer_details") {
    return {
      error: {
        message:
          `Cannot start file upload from status ${session.status}`,
      },
    };
  }

  // 3. Transition
  const {
    data,
    error,
  } = await supabaseAdmin
    .from("print_sessions")
    .update({
      status: "files_uploading",
    })
    .eq("id", session.id)
    .eq("status", "customer_details")
    .select()
    .single();

  if (error) {
    return {
      error,
    };
  }

  return {
    data,
  };
}



